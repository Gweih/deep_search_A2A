# 加载配置文件方便后续使用
def get_db_config():
    """Get database configuration from environment variables."""
    config = {
        "host": os.getenv("MYSQL_HOST", "localhost"),
        "port": int(os.getenv("MYSQL_PORT", "3306")),
        "user": os.getenv("MYSQL_USER"),
        "password": os.getenv("MYSQL_PASSWORD"),
        "database": os.getenv("MYSQL_DATABASE"),
        "charset": os.getenv("MYSQL_CHARSET", "utf8mb4"),
        "collation": os.getenv("MYSQL_COLLATION", "utf8mb4_unicode_ci"),
        "autocommit": True,
        "sql_mode": os.getenv("MYSQL_SQL_MODE", "TRADITIONAL")
    }
    # 移除 None 值
    config = {k: v for k, v in config.items() if v is not None}

    # 校验核心配置是否存在
    required_keys = ["user", "password", "database"]
    missing_keys = [k for k in required_keys if k not in config]
    if missing_keys:
        raise ValueError(f"缺失数据库核心配置：{', '.join(missing_keys)}")

    return config

# 创建list_sql_tables工具 # 列出数据库中所有可用的表
@tool
def list_sql_tables() ->str:
    """
    查询当前库中所有可用的表！
    作用：为了模型识别有哪些可用的表！方便进行后续的自定义sql查询
    :return: 有表： 可用的表有：表1,表2,表3....  没有表: 没有可用的表   出现异常：查询出现异常：异常信息
    """
    monitor.report_tool(tool_name="数据库查询工具:list_sql_tables",args={})

    # 加载数据库配置
    config = get_db_config()

    # 创建sql与python之间的链接
    try:
        # 资源使用完毕后释放with
        with connect(**config) as conn:
            with conn.cursor() as cursor:
                sql = "SHOW TABLES"
                cursor.execute(sql)
                tables = cursor.fetchall() # 捕捉执行结果,要所有的表名称
                if not tables:
                    return "没有可用的表"
                table_names = [table[0] for table in tables] # 取出所有的表
                return f"可用的表有:{', '.join(table_names)}"
    except Error as e:
        return f"查询出现异常:{str(e)}"

