# 读取指定表的前100行数据，用于快速预览数据内容
@tool
def get_table_data(table_name)->str:
    """
    查询指定表名的数据！当前工具调用之前，必须先调用list_sql_tables完成表名的校验！
    此工具的作用：1.可以完成单表数据的查询 2. 可以为多表查询提供表结果信息（列名&数据格式）
    :param table_name: 表名
    :return: csv格式的数据（模拟表格数据格式）
             1.第一行是列信息，列之间使用,（英文的逗号）分割
             2.第二行开始是表数据，值之间也使用,(英文的逗号)分割
             3.行和行之间使用\n分割
             4.至多表数据查询100条
             例如：
                id,name,age\n -> 列头
                1,张三,18\n
                1,张三,18\n    -> 至多查询100条
                1,张三,18\n
                1,张三,18\n
    """
    # 向前端推送调用信息
    monitor.report_tool(tool_name="数据库查询工具:get_table_data", args={})

    # 加载数据库配置
    config = get_db_config()

    # 创建sql与python之间的链接
    try:
        with connect(**config) as conn:
            with conn.cursor() as cursor:
                # 返回前100条数据
                cursor.execute(f"SELECT * FROM {table_name} LIMIT 100")
                # 返回结果集的列元信息（每一列的名称、类型、长度等） -> 如果查询不到结果,那么description = NONE
                description = cursor.description
                if not description:
                    return f"数据表:{table_name}为空,没有数据"
                # 获取查询首行的结果 ['列名1','列名2',...]
                columns = [desc[0] for desc in description] # 获取所有数据行
                # 获取每行的所有数据 例:[(1, 'A', 25), (2, 'B', 30),...]
                rows = cursor.fetchall()
                # 将数据转变为 ['1, A, 25' , '2, B, 30' , ...] 的格式
                results = [",".join(map(str, row)) for row in rows]
                # 列名1,列名2,...
                header_str = ",".join(columns)
                # '1, A, 25'\n
                data_str = "\n".join(results)
                # 将其制成CSV格式字符串
                return f"{header_str}\n{data_str}"
    except Error as e:
        return f"查询出现异常:{str(e)}"


