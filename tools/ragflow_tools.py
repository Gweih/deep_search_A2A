# 创建一个ragflow的客户端
api_key , base_url =_load_ragflow_env()
ragflow_client = RAGFlow(api_key=api_key,base_url=base_url)

# 查询现在知识库中有哪些聊天助手和对应知识库的信息 （方便我们知道rag可以给我们提供哪些数据） # 向前端推送调用信息
@tool
def get_assistant_list() -> str:
    """
    调用此工具，可以查询ragflow服务器中有哪些助手和助手关联的知识库信息！
    供模型参考，可以从哪个助手获取对应的内部文档信息！
    强调：想向某个助手提问，必须想要调用此工具查询助手的信息和名称
    返回结果： 有-> 名称:助手名称,助手描述：xxxx,关联的知识库：知识库的名、知识库的名字、
             没有 -> 没有任何可用助手
             异常 -> 查询助手信息异常，无可用助手
    :return:
    """
    monitor.report_tool(tool_name="ragflow聊天助手列表查询工具：get_assistant_list")

    try:
        chat_list = ragflow_client.list_chats() # ragflow客户端查询所有的聊天助手 原码默认查询第一个到第三十个
        if not chat_list:
            return "没有任何可用助手"
        # 查询聊天助手的知识库信息
        count_chat_info = "" # 存储所有会话信息
        for chat in chat_list:
            dataset_names = [] # 用来存储助手的所有知识库
            dataset_list = chat.datasets # 查询聊天助手关联的知识库
            if dataset_list and isinstance(dataset_list,list): # 拿到所有的知识库信息
                for dataset in dataset_list: # 取出知识库的名字
                    dataset_names.append(dataset['name']) # 将一个助手的知识库的名字加入到列表中
            count_chat_info += f"助手名称:{chat.name};功能介绍：{chat.description}; 关联的知识库：{'、'.join(dataset_names)} \n"  # 拼接下助手的信息+知识库信息
        return count_chat_info  # 返回所有信息供模型参考
    except Exception as e:
        return f"查询助手信息异常，无可用助手,异常信息:{str(e)}"

# 对助手进行提问 # 向前端推送调用信息 # 助手名字 or 问题
@tool
def create_ask_delete(chat_name,question)->str:
    """
    想某个助手，创建单次会话进行提问，提问完毕以后会关闭会话！
    主要查询ragflow中相关的信息！
    注意：调用此工具之前，必须先调用 get_assistant_list工具明确查询助手的名字和对应的问题
    :param chat_name: 助手的名字！上一个工具get_assistant_list告诉大模型的只有名字
    :param question: 本次提问的问题
    :return: 返回提问的结果
    """
    monitor.report_tool(tool_name="ragflow提问助手工具：create_ask_delete",args={"chat_name":chat_name,"question":question})
    try:
        chats = ragflow_client.list_chats(name=chat_name) # 查询名字对应的助手
        use_chat = chats[0] #选中助手
        session = use_chat.create_session(name="temp_session_ask") # 在助手上创建新对话
        response = session.ask(question = question,stream=True) # 提出问题,并返回流式回答
        result = "" # 用于接收回答
        for part in response: # 获取流式输出的数据
            result = part.content # 将数据存在对象中content上 这里的流式输出不是块,是包含前面输出内容,所以是=不是+=
        use_chat.delete_sessions(ids=[session.id]) # TODO:关闭提问的会话
        return result  # 返回结果
    except Exception as e:
        return f"提问失败，错误原因：{str(e)}"

